// 当前页面对应的说明：视频脚本按标签页区分
export function helpKey() {
  const [, path = '', sub = ''] = location.hash.split('/');
  if (path === 'scripts' && ['create', 'studio', 'viral', 'videos', 'playbook'].includes(sub)) return `scripts/${sub}`;
  return HELP[path] ? path : '';
}

export const helpHTML = (h) => `<p class="help-what">${esc(h.what)}</p>
  <h4 class="help-h">怎么用</h4><ol class="help-steps">${h.steps.map((s) => `<li>${esc(s)}</li>`).join('')}</ol>
  ${h.tips?.length ? `<h4 class="help-h">注意</h4><ul class="help-tips">${h.tips.map((s) => `<li>${esc(s)}</li>`).join('')}</ul>` : ''}`;

// 右侧抽屉
export function openHelp(key = helpKey()) {
  document.querySelector('.help-drawer')?.remove();
  const h = HELP[key];
  const el = document.createElement('div');
  el.className = 'help-drawer';
  el.innerHTML = `<div class="help-mask" data-close></div><aside class="help-panel" role="dialog" aria-label="使用说明">
    <div class="help-top"><b>${icon('book', 16)}${esc(h ? h.title : '使用说明')}</b><button class="icon-btn" data-close aria-label="关闭">${icon('x')}</button></div>
    <div class="help-body">${h ? helpHTML(h) : '<p class="muted">这个页面没有单独的说明。</p>'}
      <a class="btn sm ghost" href="#/guide" data-close>${icon('layers', 14)}查看全部功能的使用指南</a></div></aside>`;
  const close = () => {
    el.classList.add('out');
    setTimeout(() => el.remove(), 200);
    removeEventListener('keydown', onKey);
  };
  const onKey = (e) => e.key === 'Escape' && close();
  el.addEventListener('click', (e) => e.target.closest('[data-close]') && close());
  addEventListener('keydown', onKey);
  document.body.appendChild(el);
  $('.help-panel', el).focus?.();
}
